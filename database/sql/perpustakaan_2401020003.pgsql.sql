CREATE TABLE IF NOT EXISTS kategori_buku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS buku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_buku CHAR(10) NOT NULL UNIQUE,
    judul VARCHAR(100) NOT NULL,
    isbn CHAR(13) NOT NULL UNIQUE,
    tahun_terbit SMALLINT NOT NULL
        CHECK (tahun_terbit BETWEEN 2000 AND 2026),
    kategori_buku_id BIGINT NOT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    CONSTRAINT buku_kategori_buku_id_foreign
        FOREIGN KEY (kategori_buku_id)
        REFERENCES kategori_buku (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS buku_kategori_buku_id_index
    ON buku (kategori_buku_id);

